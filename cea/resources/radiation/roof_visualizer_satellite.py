def main() -> None:
    args = parse_args()
    if args.bar_scale_m_per_mwh <= 0:
        raise ValueError("--bar-scale-m-per-mwh must be greater than zero.")
    if args.min_bar_height_m < 0:
        raise ValueError("--min-bar-height-m must be non-negative.")
    if args.bar_width_m <= 0:
        raise ValueError("--bar-width-m must be greater than zero.")
    if args.coordinate_precision < 0:
        raise ValueError("--coordinate-precision must be non-negative.")
    if args.flat_threshold_deg < 0:
        raise ValueError("--flat-threshold-deg must be non-negative.")
    if args.satellite_opacity < 0 or args.satellite_opacity > 1:
        raise ValueError("--satellite-opacity must be between 0 and 1.")

    scenario = os.path.abspath(args.scenario)
    if not os.path.isdir(scenario):
        raise NotADirectoryError(f"Scenario folder does not exist: {scenario}")

    locator = InputLocator(scenario)
    roof_file_path = base._resolve_path(base._default_roof_file_path(scenario), args.roof_file)
    roofs, roof_stats, roof_quality = base._load_roofs(
        roof_file_path=roof_file_path,
        precision=args.coordinate_precision,
        flat_threshold_deg=float(args.flat_threshold_deg),
    )
    zone, zone_centroids, centre, bounds, zone_heights_by_building, zone_buildings = base._load_zone_payload(
        locator=locator,
        roof_stats=roof_stats,
        precision=args.coordinate_precision,
    )

    pv_metrics_by_building, pv_source_path = base._load_pv_metrics_by_building(locator, args.pv_panel)
    pv_panel_efficiency, pv_panel_code = base._load_pv_panel_efficiency(locator, args.pv_panel)
    roof_availability_by_building, _, roof_availability_source_path = base._load_panel_placement_orientation_by_building(
        locator, args.pv_panel
    )

    solar_by_building = {
        building: float(metrics.get("E_PV_gen_kWh", 0.0))
        for building, metrics in pv_metrics_by_building.items()
    }
    bars = base._build_solar_bars(
        roof_stats=roof_stats,
        zone_centroids=zone_centroids,
        zone_heights_by_building=zone_heights_by_building,
        solar_by_building_kwh=solar_by_building,
        bar_color_scale=str(args.bar_color_scale),
        bar_scale_m_per_mwh=float(args.bar_scale_m_per_mwh),
        min_bar_height_m=float(args.min_bar_height_m),
        bar_width_m=float(args.bar_width_m),
        precision=args.coordinate_precision,
    )
    _, bar_color_distribution = base._build_bar_color_ratios(
        solar_by_building_kwh=solar_by_building,
        bar_color_scale=str(args.bar_color_scale),
    )
    kpis, building_metrics = base._build_decision_metrics(
        zone_buildings=zone_buildings,
        zone_heights_by_building=zone_heights_by_building,
        roof_stats=roof_stats,
        roof_quality=roof_quality,
        pv_metrics_by_building=pv_metrics_by_building,
        pv_source_path=pv_source_path,
        pv_panel_efficiency=pv_panel_efficiency,
        pv_panel_code=pv_panel_code,
        roof_availability_by_building=roof_availability_by_building,
        roof_availability_source_path=roof_availability_source_path,
    )

    scenario_bounds = {
        "west": bounds[0],
        "south": bounds[1],
        "east": bounds[2],
        "north": bounds[3],
    }
    satellite_image_path = base._resolve_path(_default_satellite_image_path(scenario), args.satellite_image)
    satellite_signature_path = base._resolve_path(_default_signature_path(scenario), args.satellite_signature)
    satellite_payload = _build_satellite_payload(
        image_path=satellite_image_path,
        signature_path=satellite_signature_path,
        fallback_bounds=scenario_bounds,
        opacity=float(args.satellite_opacity),
        visible=bool(args.show_satellite),
    )

    payload = {
        "scenario": scenario,
        "pv_panel": str(args.pv_panel),
        "pv_panel_code": pv_panel_code,
        "pv_panel_efficiency": pv_panel_efficiency,
        "flat_threshold_deg": float(args.flat_threshold_deg),
        "bar_color_scale": str(args.bar_color_scale),
        "bar_color_distribution": bar_color_distribution,
        "map_style": args.map_style,
        "zone": zone,
        "roofs": roofs,
        "bars": bars,
        "kpis": kpis,
        "building_metrics": building_metrics,
        "roof_quality": roof_quality,
        "centre_lat": centre[0],
        "centre_lon": centre[1],
        "bounds": scenario_bounds,
        "roof_file_path": roof_file_path,
        "pv_source_path": pv_source_path,
        "roof_availability_source_path": roof_availability_source_path,
        "satellite": satellite_payload,
    }

    output_path = base._resolve_path(_default_output_html_path(scenario), args.output_html)
    render_html(output_path, payload)
    print("[ok] Roof visualizer with satellite generated.")
    print(f"Buildings loaded: {len(zone.get('features', []))}")
    print(f"Roofs loaded: {len(roofs)}")
    print(f"Solar bars loaded: {len(bars)}")
    print(f"Bar color scale: {args.bar_color_scale}")
    print(f"PV source: {pv_source_path or '(not found)'}")
    print(f"Roof availability source: {roof_availability_source_path or '(not found)'}")
    print(f"PV panel efficiency (PV_n): {pv_panel_efficiency if pv_panel_efficiency is not None else '(not found)'}")
    print(f"Satellite status: {satellite_payload.get('status')}")
    print(f"Satellite file: {satellite_payload.get('image_path') or '(not found)'}")
    print(f"Satellite bounds source: {satellite_payload.get('bounds_source') or '(none)'}")
    print(f"Output HTML: {output_path}")


if __name__ == "__main__":
    main()
