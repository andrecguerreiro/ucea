def _default_output_html_path(scenario: str) -> str:
    return os.path.join(os.path.abspath(scenario), DEFAULT_OUTPUT_HTML)


def _resolve_repo_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))


def _default_satellite_image_path(scenario: str) -> str:
    scenario_candidate = os.path.join(
        os.path.abspath(scenario),
        DEFAULT_SCENARIO_SATELLITE_IMAGE_RELATIVE_PATH,
    )
    if os.path.exists(scenario_candidate):
        return scenario_candidate

    repo_root = _resolve_repo_root()
    repo_candidates = [
        os.path.join(repo_root, relative_path)
        for relative_path in DEFAULT_SATELLITE_IMAGE_CANDIDATE_RELATIVE_PATHS
    ]
    for candidate in repo_candidates:
        if os.path.exists(candidate):
            return candidate
    return repo_candidates[0]


def _default_signature_path(scenario: str) -> str:
    return os.path.join(os.path.abspath(scenario), DEFAULT_SATELLITE_SIGNATURE_RELATIVE_PATH)


def _normalise_ring(points: Any) -> list[list[float]] | None:
    if not isinstance(points, list):
        return None

    cleaned: list[list[float]] = []
    for point in points:
        if not isinstance(point, (list, tuple)) or len(point) < 2:
            continue
        try:
            lon = float(point[0])
            lat = float(point[1])
        except (TypeError, ValueError):
            continue
        if not (math.isfinite(lon) and math.isfinite(lat)):
            continue
        cleaned.append([lon, lat])

    if len(cleaned) < 3:
        return None
    if cleaned[0] != cleaned[-1]:
        cleaned.append(cleaned[0])
    return cleaned


def _bounds_from_ring(ring: list[list[float]]) -> dict[str, float]:
    lons = [point[0] for point in ring]
    lats = [point[1] for point in ring]
    return {
        "west": float(min(lons)),
        "south": float(min(lats)),
        "east": float(max(lons)),
        "north": float(max(lats)),
    }


def _load_bounds_from_signature(signature_path: str) -> tuple[dict[str, float] | None, str | None]:
    if not signature_path or not os.path.exists(signature_path):
        return None, None
    try:
        with open(signature_path, "r", encoding="utf-8") as fp:
            payload = json.load(fp)
    except (OSError, json.JSONDecodeError):
        return None, None

    ring = _normalise_ring(payload.get("polygon_ring_lon_lat"))
    if not ring:
        return None, None
    return _bounds_from_ring(ring), signature_path


def _image_to_data_uri(image_path: str) -> str:
    with open(image_path, "rb") as fp:
        encoded = base64.b64encode(fp.read()).decode("ascii")
    mime_type = mimetypes.guess_type(image_path)[0] or "image/png"
    return f"data:{mime_type};base64,{encoded}"


def _build_satellite_payload(
    *,
    image_path: str,
    signature_path: str,
    fallback_bounds: dict[str, float],
    opacity: float,
    visible: bool,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "available": False,
        "visible": bool(visible),
        "opacity": float(opacity),
        "image_path": image_path if image_path else None,
        "signature_path": signature_path if signature_path else None,
        "bounds": None,
        "bounds_source": None,
        "image_data_uri": None,
        "status": "Satellite image not configured.",
    }

    if not image_path or not os.path.exists(image_path):
        payload["status"] = "Satellite image file not found."
        return payload

    bounds, resolved_signature_path = _load_bounds_from_signature(signature_path)
    if bounds is not None:
        payload["bounds"] = bounds
        payload["bounds_source"] = "roof input signature"
        payload["signature_path"] = resolved_signature_path
    else:
        payload["bounds"] = fallback_bounds
        payload["bounds_source"] = "zone bounds fallback"

    try:
        payload["image_data_uri"] = _image_to_data_uri(image_path)
    except OSError:
        payload["status"] = "Satellite image could not be read."
        return payload

    payload["available"] = True
    payload["status"] = "Satellite layer ready."
    return payload


