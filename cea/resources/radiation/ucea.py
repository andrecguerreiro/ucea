def _normalise_polygon_ring(coordinates: list[tuple[float, float]]) -> list[list[float]]:
    if len(coordinates) < 3:
        raise ValueError("Polygon requires at least three coordinate pairs.")

    ring = [[float(lon), float(lat)] for lon, lat in coordinates]
    if ring[0] != ring[-1]:
        ring.append(ring[0])
    return ring


