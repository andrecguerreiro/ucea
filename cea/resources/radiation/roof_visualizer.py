    candidates = [
        default_satellite_image_path(scenario),
        os.path.join(os.path.dirname(default_roof_file_path(scenario)), "satellite_image.png"),
    ]
    for candidate in candidates:
        if os.path.exists(candidate):
            return candidate
    return candidates[0]


