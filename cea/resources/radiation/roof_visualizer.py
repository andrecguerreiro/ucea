def _parse_height_m(value: Any) -> float | None:
    if value is None:
        return None
    text = str(value).strip().lower()
    if not text:
        return None
    text = text.replace(",", ".")
    match = re.search(r"-?\d+(\.\d+)?", text)
    if match is None:
        return None
    try:
        parsed = float(match.group(0))
    except ValueError:
        return None
    return parsed if parsed > 0 else None


def _parse_levels_to_height_m(levels_value: Any) -> float | None:
    levels = _parse_height_m(levels_value)
    if levels is None:
        return None
    return max(3.0, levels * 3.0)


def _load_zone_site_polygon_wgs84(locator: InputLocator):
    gpd = _import_geopandas()
    Polygon, _, unary_union = _import_shapely()

    site_path = locator.get_site_polygon()
    if not os.path.exists(site_path):
        raise FileNotFoundError(f"Site polygon not found: {site_path}")

    site_gdf = gpd.read_file(site_path)
    site_gdf = site_gdf[~site_gdf.geometry.is_empty & site_gdf.geometry.notna()].copy()
    if site_gdf.empty:
        raise ValueError("Site polygon is empty.")

    site_wgs84 = site_gdf.to_crs(epsg=4326)
    site_union = unary_union(site_wgs84.geometry.values.tolist())
    if site_union.is_empty:
        raise ValueError("Site polygon is empty after CRS conversion.")
    if not isinstance(site_union, Polygon) and site_union.geom_type != "MultiPolygon":
        raise ValueError("Site polygon geometry type is not polygonal.")
    return site_union


def _site_bounds(site_polygon) -> tuple[float, float, float, float]:
    minx, miny, maxx, maxy = site_polygon.bounds
    return float(minx), float(miny), float(maxx), float(maxy)


def _wmts_get_tile_indices(xmin: float, ymin: float, xmax: float, ymax: float, matrix) -> tuple[int, int, int, int]:
    tile_size = matrix.tilewidth * matrix.scaledenominator * 0.28e-3
    origin_x, origin_y = matrix.topleftcorner
    col_min = int((xmin - origin_x) // tile_size)
    col_max = int((xmax - origin_x) // tile_size)
    row_min = int((origin_y - ymax) // tile_size)
    row_max = int((origin_y - ymin) // tile_size)
    return col_min, col_max, row_min, row_max


def _retrieve_satellite_image_from_bbox(
    top_left_corner_3763: tuple[float, float],
    bottom_right_corner_3763: tuple[float, float],
    tile_cache_dir: str,
) -> np.ndarray:
    WebMapTileService = _import_wmts()
    Image = _import_pillow_image()

    wmts_url = (
        "https://cartografia.dgterritorio.gov.pt/ortos2018/service"
        "?service=WMTS&request=GetCapabilities"
    )
    wmts = WebMapTileService(wmts_url)
    layer = "Ortos2018-RGB"
    tile_matrix_set = "PTTM_06"
    zoom_level = "14"
    matrix = wmts.tilematrixsets[tile_matrix_set].tilematrix[zoom_level]
    res = matrix.scaledenominator * 0.28e-3
    tile_size_m = matrix.tilewidth * res

    xmin, ymax = top_left_corner_3763
    xmax, ymin = bottom_right_corner_3763
    col_min, col_max, row_min, row_max = _wmts_get_tile_indices(xmin, ymin, xmax, ymax, matrix)
    n_rows = row_max + 1 - row_min
    n_cols = col_max + 1 - col_min
    processed_blocks = np.empty((n_rows, n_cols), dtype=object)

    os.makedirs(tile_cache_dir, exist_ok=True)
    for row in range(row_min, row_max + 1):
        for col in range(col_min, col_max + 1):
            tile_filename = os.path.join(tile_cache_dir, f"tile_{zoom_level}_{row}_{col}.png")
            if os.path.exists(tile_filename):
                img_array = np.array(Image.open(tile_filename).convert("RGB"))
            else:
                tile = wmts.gettile(
                    layer=layer,
                    tilematrixset=tile_matrix_set,
                    tilematrix=zoom_level,
                    row=row,
                    column=col,
                    format="image/png",
                )
                img = Image.open(io.BytesIO(tile.read())).convert("RGB")
                img.save(tile_filename)
                img_array = np.array(img)
            processed_blocks[row - row_min, col - col_min] = {"img": img_array}

    block_h, block_w = processed_blocks[0, 0]["img"].shape[:2]
    stitched = np.zeros((n_rows * block_h, n_cols * block_w, 3), dtype=np.uint8)
    for row in range(n_rows):
        for col in range(n_cols):
            stitched[row * block_h:(row + 1) * block_h, col * block_w:(col + 1) * block_w] = processed_blocks[row, col]["img"]

    origin_x = matrix.topleftcorner[0] + col_min * tile_size_m
    origin_y = matrix.topleftcorner[1] - row_min * tile_size_m

    col_start = int(round((xmin - origin_x) / res))
    row_start = int(round((origin_y - ymax) / res))
    col_end = int(round((xmax - origin_x) / res))
    row_end = int(round((origin_y - ymin) / res))
    return stitched[row_start:row_end, col_start:col_end, :]


def _ensure_matching_satellite_image(
    scenario: str,
    requested_satellite_path: str,
    roof_file_path: str,
    site_bounds_wgs84: tuple[float, float, float, float],
) -> str:
    west, south, east, north = site_bounds_wgs84
    target_path = requested_satellite_path
    if not os.path.isabs(target_path):
        target_path = os.path.abspath(target_path)
    os.makedirs(os.path.dirname(target_path), exist_ok=True)

    must_regenerate = not os.path.exists(target_path)
    if os.path.exists(target_path) and os.path.exists(roof_file_path):
        sat_mtime = os.path.getmtime(target_path)
        roof_mtime = os.path.getmtime(roof_file_path)
        if sat_mtime < roof_mtime:
            must_regenerate = True

    if not must_regenerate:
        return target_path

    print("[info] Generating scenario-matching satellite image from WMTS...")
    transformer = Transformer.from_crs("EPSG:4326", "EPSG:3763", always_xy=True)
    tl_x, tl_y = transformer.transform(west, north)
    br_x, br_y = transformer.transform(east, south)
    top_left = (float(tl_x), float(tl_y))
    bottom_right = (float(br_x), float(br_y))
    tile_cache_dir = os.path.join(os.path.abspath(os.path.dirname(__file__)), "cache", "tiles")

    image = _retrieve_satellite_image_from_bbox(
        top_left_corner_3763=top_left,
        bottom_right_corner_3763=bottom_right,
        tile_cache_dir=tile_cache_dir,
    )
    Image = _import_pillow_image()
    Image.fromarray(image).save(target_path)
    print(f"[ok] Satellite image generated: {target_path}")
    return target_path


def _fetch_osm_buildings_for_site(site_polygon, cache_dir: str) -> dict[str, Any]:
    _, shapely_shape, _ = _import_shapely()

    west, south, east, north = _site_bounds(site_polygon)
    query = (
        "[out:json][timeout:180];"
        f"(way[\"building\"]({south},{west},{north},{east});"
        f"relation[\"building\"]({south},{west},{north},{east}););"
        "out body;>;out skel qt;"
    )

    os.makedirs(cache_dir, exist_ok=True)
    key = hashlib.md5(f"{south:.8f}|{west:.8f}|{north:.8f}|{east:.8f}".encode("utf-8")).hexdigest()
    cache_path = os.path.join(cache_dir, f"osm_buildings_{key}.json")
    if os.path.exists(cache_path):
        with open(cache_path, "r", encoding="utf-8") as fp:
            return json.load(fp)

    fetch_errors: list[str] = []
    data: dict[str, Any] | None = None
    for endpoint in OVERPASS_ENDPOINTS:
        for attempt in range(1, OVERPASS_RETRIES_PER_ENDPOINT + 1):
            try:
                response = requests.post(endpoint, data=query, timeout=OVERPASS_TIMEOUT_SECONDS)
                response.raise_for_status()
                data = response.json()
                print(f"[info] OSM buildings fetched via: {endpoint}")
                break
            except requests.RequestException as exc:
                fetch_errors.append(f"{endpoint} [attempt {attempt}]: {exc}")
                if attempt < OVERPASS_RETRIES_PER_ENDPOINT:
                    sleep_seconds = 1.5 * attempt
                    print(
                        f"[warn] Overpass request failed ({endpoint}, attempt {attempt}/"
                        f"{OVERPASS_RETRIES_PER_ENDPOINT}). Retrying in {sleep_seconds:.1f}s..."
                    )
                    time.sleep(sleep_seconds)
                continue
            except ValueError as exc:
                fetch_errors.append(f"{endpoint} [attempt {attempt}]: invalid JSON ({exc})")
                continue
        if data is not None:
            break

    if data is None:
        joined = "\n".join(fetch_errors) if fetch_errors else "(no request details)"
        raise RuntimeError(
            "Could not fetch OSM buildings from Overpass endpoints.\n"
            f"Bounding box: south={south:.6f}, west={west:.6f}, north={north:.6f}, east={east:.6f}\n"
            "Tried endpoints:\n"
            f"{chr(10).join(OVERPASS_ENDPOINTS)}\n"
            "Request errors:\n"
            f"{joined}"
        )

    nodes = {
        el["id"]: (float(el["lon"]), float(el["lat"]))
        for el in data.get("elements", [])
        if el.get("type") == "node"
    }

    raw_features: list[dict[str, Any]] = []
    for element in data.get("elements", []):
        if element.get("type") != "way":
            continue
        node_ids = element.get("nodes", [])
        coords = [nodes[nid] for nid in node_ids if nid in nodes]
        if len(coords) < 3:
            continue
        raw_features.append(
            {
                "type": "Feature",
                "properties": {"osm_id": str(element.get("id", "")), **element.get("tags", {})},
                "geometry": {"type": "Polygon", "coordinates": [coords]},
            }
        )

    filtered_features: list[dict[str, Any]] = []
    for feature in raw_features:
        try:
            geom = shapely_shape(feature["geometry"])
        except Exception:
            continue
        if geom.is_empty:
            continue
        if not geom.intersects(site_polygon):
            continue
        filtered_features.append(feature)

    feature_collection = {"type": "FeatureCollection", "features": filtered_features}
    with open(cache_path, "w", encoding="utf-8") as fp:
        json.dump(feature_collection, fp, ensure_ascii=False, indent=2)
    return feature_collection


def _load_roof_surfaces(roof_file_path: str) -> list[dict[str, Any]]:
    if not os.path.exists(roof_file_path):
        raise FileNotFoundError(f"Roof surfaces file not found: {roof_file_path}")

    with open(roof_file_path, "r", encoding="utf-8") as fp:
        roof_obj = json.load(fp)

    if not isinstance(roof_obj, dict) or roof_obj.get("type") != "FeatureCollection":
        raise ValueError(f"Roof file is not a FeatureCollection: {roof_file_path}")

    source_crs = parse_geojson_crs_name(roof_obj, fallback_crs="EPSG:32629")
    transformer = Transformer.from_crs(source_crs, "EPSG:4326", always_xy=True)

    roofs: list[dict[str, Any]] = []
    features = roof_obj.get("features", [])
    if not isinstance(features, list):
        return roofs

    for feature in features:
        if not isinstance(feature, dict):
            continue
        properties = feature.get("properties", {})
        geometry = feature.get("geometry", {})
        if not isinstance(properties, dict) or not isinstance(geometry, dict):
            continue

        geometry_type = str(geometry.get("type", ""))
        coordinates = geometry.get("coordinates")
        if not isinstance(coordinates, list):
            continue

        building_name = str(properties.get("building", "")).strip()
        roof_id = str(properties.get("roof_id", "")).strip()
        rings = _iter_polygon_rings(geometry_type, coordinates)
        for ring in rings:
            if not isinstance(ring, list) or len(ring) < 3:
                continue
            points_wgs84: list[list[float]] = []
            valid = True
            for point in ring:
                if not isinstance(point, list) or len(point) < 3:
                    valid = False
                    break
                x = float(point[0])
                y = float(point[1])
                z = float(point[2])
                lon, lat = transformer.transform(x, y)
                points_wgs84.append([float(lon), float(lat), z])
            if not valid:
                continue

            ordered_ring = _ordered_ring_from_points_3d(points_wgs84)
            if ordered_ring is None:
                continue

            z_values = [pt[2] for pt in ordered_ring]
            roofs.append(
                {
                    "building": building_name,
                    "roof_id": roof_id,
                    "polygon": ordered_ring,
                    "z_min": float(min(z_values)),
                    "z_max": float(max(z_values)),
                    "z_mean": float(sum(z_values) / max(1, len(z_values))),
                }
            )
    return roofs


def _apply_osm_heights(osm_geojson: dict[str, Any], roofs: list[dict[str, Any]]) -> dict[str, Any]:
    Polygon, shapely_shape, _ = _import_shapely()

    roof_polys = []
    for roof in roofs:
        polygon_coords = roof.get("polygon", [])
        if not isinstance(polygon_coords, list) or len(polygon_coords) < 4:
            continue
        coords_2d = [(float(p[0]), float(p[1])) for p in polygon_coords if isinstance(p, list) and len(p) >= 2]
        if len(coords_2d) < 4:
            continue
        try:
            poly = Polygon(coords_2d)
        except Exception:
            continue
        if poly.is_empty:
            continue
        roof_polys.append((poly, float(roof.get("z_min", DEFAULT_OSM_HEIGHT_M))))

    features = osm_geojson.get("features", [])
    if not isinstance(features, list):
        return osm_geojson

    for feature in features:
        if not isinstance(feature, dict):
            continue
        geometry = feature.get("geometry")
        props = feature.get("properties")
        if not isinstance(geometry, dict) or not isinstance(props, dict):
            continue
        try:
            osm_poly = shapely_shape(geometry)
        except Exception:
            continue
        if osm_poly.is_empty:
            continue

        height_candidates = []
        for roof_poly, roof_zmin in roof_polys:
            if roof_poly.intersects(osm_poly):
                height_candidates.append(roof_zmin)

        height_tag = _parse_height_m(props.get("height"))
        level_height = _parse_levels_to_height_m(props.get("building:levels"))

        if height_candidates:
            roof_match_height = float(np.median(np.asarray(height_candidates, dtype=float)))
            viz_height = max(3.0, roof_match_height)
        elif height_tag is not None:
            viz_height = max(3.0, height_tag)
        elif level_height is not None:
            viz_height = max(3.0, level_height)
        else:
            viz_height = DEFAULT_OSM_HEIGHT_M

        props["viz_height_m"] = float(viz_height)
        props["osm_id"] = str(props.get("osm_id", ""))
    return osm_geojson


def _image_file_to_data_uri(image_path: str) -> str:
    if not os.path.exists(image_path):
        return ""
    ext = os.path.splitext(image_path)[1].lower()
    mime = "image/png"
    if ext in [".jpg", ".jpeg"]:
        mime = "image/jpeg"
    elif ext == ".webp":
        mime = "image/webp"
    with open(image_path, "rb") as fp:
        encoded = base64.b64encode(fp.read()).decode("ascii")
    return f"data:{mime};base64,{encoded}"


def _site_centre(site_polygon) -> tuple[float, float]:
    centroid = site_polygon.centroid
    return float(centroid.y), float(centroid.x)


def _candidate_pv_totals_paths(locator: InputLocator, pv_panel: str) -> list[str]:
    panel = str(pv_panel).strip()
    if not panel:
        panel = DEFAULT_PV_PANEL
    candidates: list[str] = []
    if panel.upper().startswith("PV_"):
        panel_no_prefix = panel[3:]
    else:
        panel_no_prefix = panel

    candidates.append(locator.PV_total_buildings(panel_no_prefix))
    manual_path = os.path.join(locator.solar_potential_folder(), f"PV_{panel_no_prefix}_total_buildings.csv")
    if manual_path not in candidates:
        candidates.append(manual_path)
    return candidates


def _load_solar_capacity_by_building(locator: InputLocator, pv_panel: str) -> tuple[dict[str, float], str]:
    pd = _import_pandas()
    for path in _candidate_pv_totals_paths(locator, pv_panel):
        if not os.path.exists(path):
            continue
        try:
            totals = pd.read_csv(path)
        except Exception:
            continue
        if "name" not in totals.columns or "E_PV_gen_kWh" not in totals.columns:
            continue
        totals = totals.copy()
        totals["name"] = totals["name"].astype(str)
        totals["E_PV_gen_kWh"] = pd.to_numeric(totals["E_PV_gen_kWh"], errors="coerce").fillna(0.0)
        return dict(zip(totals["name"], totals["E_PV_gen_kWh"])), path
    return {}, ""


def _load_zone_centroids_wgs84(locator: InputLocator) -> dict[str, list[float]]:
    gpd = _import_geopandas()
    zone_path = locator.get_zone_geometry()
    if not os.path.exists(zone_path):
        return {}
    zone = gpd.read_file(zone_path)
    if "name" not in zone.columns:
        return {}
    zone = zone[~zone.geometry.is_empty & zone.geometry.notna()].copy()
    if zone.empty:
        return {}
    zone["name"] = zone["name"].astype(str)
    zone_wgs84 = zone.to_crs(epsg=4326)
    result: dict[str, list[float]] = {}
    for _, row in zone_wgs84.iterrows():
        c = row.geometry.centroid
        result[str(row["name"])] = [float(c.x), float(c.y)]
    return result


def _map_colour(value: float, value_max: float, low: tuple[int, int, int], high: tuple[int, int, int]) -> list[int]:
    if value_max <= 0:
        ratio = 0.0
    else:
        ratio = max(0.0, min(1.0, value / value_max))
    return [
        int(low[0] + ratio * (high[0] - low[0])),
        int(low[1] + ratio * (high[1] - low[1])),
        int(low[2] + ratio * (high[2] - low[2])),
    ]


def _build_solar_bars_payload(
    roofs_payload: list[dict[str, Any]],
    solar_by_building_kwh: dict[str, float],
    zone_centroids_wgs84: dict[str, list[float]],
    bar_scale_m_per_mwh: float,
    min_bar_height_m: float,
    bar_width_m: float,
) -> list[dict[str, Any]]:
    if not solar_by_building_kwh:
        return []

    roof_stats: dict[str, dict[str, float]] = {}
    for roof in roofs_payload:
        building = str(roof.get("building", "")).strip()
        polygon = roof.get("polygon", [])
        if not building or not isinstance(polygon, list) or len(polygon) < 4:
            continue
        coords = [p for p in polygon if isinstance(p, list) and len(p) >= 3]
        if len(coords) < 3:
            continue
        lons = [float(p[0]) for p in coords]
        lats = [float(p[1]) for p in coords]
        zs = [float(p[2]) for p in coords]
        if building not in roof_stats:
            roof_stats[building] = {
                "lon_sum": 0.0,
                "lat_sum": 0.0,
                "count": 0.0,
                "z_top": float(max(zs)),
            }
        roof_stats[building]["lon_sum"] += float(sum(lons))
        roof_stats[building]["lat_sum"] += float(sum(lats))
        roof_stats[building]["count"] += float(len(coords))
        roof_stats[building]["z_top"] = max(float(roof_stats[building]["z_top"]), float(max(zs)))

    max_solar_kwh = max([float(v) for v in solar_by_building_kwh.values()], default=0.0)
    low = (255, 204, 102)
    high = (226, 71, 23)
    bars: list[dict[str, Any]] = []
    for building, solar_kwh_raw in solar_by_building_kwh.items():
        solar_kwh = float(solar_kwh_raw)
        solar_mwh = solar_kwh / 1000.0
        if solar_mwh <= 0.0:
            continue

        if building in roof_stats and roof_stats[building]["count"] > 0:
            lon = roof_stats[building]["lon_sum"] / roof_stats[building]["count"]
            lat = roof_stats[building]["lat_sum"] / roof_stats[building]["count"]
            base_height_m = float(roof_stats[building]["z_top"]) + DEFAULT_BAR_BASE_OFFSET_M
        else:
            centroid = zone_centroids_wgs84.get(building)
            if centroid is None:
                continue
            lon = float(centroid[0])
            lat = float(centroid[1])
            base_height_m = DEFAULT_OSM_HEIGHT_M + DEFAULT_BAR_BASE_OFFSET_M

        bar_height_m = max(min_bar_height_m, solar_mwh * bar_scale_m_per_mwh)
        bars.append(
            {
                "building": building,
                "solar_kwh": solar_kwh,
                "solar_mwh": solar_mwh,
                "base_height_m": base_height_m,
                "bar_height_m": bar_height_m,
                "bar_width_m": float(bar_width_m),
                "source_position": [lon, lat, base_height_m],
                "target_position": [lon, lat, base_height_m + bar_height_m],
                "bar_colour": _map_colour(solar_kwh, max_solar_kwh, low, high),
            }
        )
    return bars


